"""Encode the Storm Cloud scene and a restrained early-boot rain sequence."""
from itertools import groupby
from pathlib import Path
import struct
import zlib

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
W, H = 320, 172
CW, CH = 156, 80

def rgb565(pixel):
    r, g, b = pixel
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)

def array(name, values, kind):
    rows = [", ".join(map(str, values[i:i + 24])) for i in range(0, len(values), 24)]
    return f"static const {kind} {name}[] = {{\n" + ",\n".join(rows) + "\n};\n"

def header(path, *arrays):
    (ROOT / "src" / path).write_text(
        "// Generated by tools/encode_weather.py.\n#pragma once\n#include <stdint.h>\n\n"
        + "\n".join(arrays)
    )

def indexed(image, colors, alpha=None):
    indexed_image = image.convert("RGB").quantize(colors=colors, dither=Image.Dither.NONE)
    table = indexed_image.getpalette()
    palette = [0] + [rgb565(table[i:i + 3]) for i in range(0, colors * 3, 3)]
    mask = alpha.tobytes() if alpha is not None else bytes([255]) * (image.width * image.height)
    return palette, [index + 1 if opacity >= 128 else 0
                     for index, opacity in zip(indexed_image.tobytes(), mask)]

valley = Image.open(ROOT / "assets/valley-v2.png").convert("RGB").resize((W, H), Image.Resampling.LANCZOS)
cloud = Image.open(ROOT / "assets/cloud-v2.png").convert("RGBA").resize((CW, CH), Image.Resampling.LANCZOS)
alpha = cloud.getchannel("A")
assert alpha.getextrema() == (0, 255)
valley_palette, valley_pixels = indexed(valley, 128)
cloud_palette, cloud_pixels = indexed(cloud, 96, alpha)
header("weather.h", array("kValleyPalette", valley_palette, "uint16_t"),
       array("kCloudPalette", cloud_palette, "uint16_t"),
       array("kValleyPixels", valley_pixels, "uint8_t"),
       array("kCloudPixels", cloud_pixels, "uint8_t"),
       "static const kit::Sprite kValley = {320, 172, 0, 0, kValleyPixels};\n"
       "static const kit::Sprite kFeltCloud = {156, 80, -78, -40, kCloudPixels};\n")

mask = alpha.resize((78, 40), Image.Resampling.LANCZOS).point(lambda v: 255 if v >= 128 else 0)
frames = []
for i in range(19):
    frame = Image.new("RGB", (W, H))
    gain = min(i / 5, 1.0, (18 - i) / 6)
    flash = 16 if i in (10, 12) else 0
    shade = tuple(round(v * gain) for v in (42 + flash, 55 + flash, 79 + flash))
    frame.paste(shade, (113, 28 - round(7 * (1 - gain))), mask)
    draw = ImageDraw.Draw(frame)
    for k in range(14):
        x = 87 + k * 10
        y = 65 + (k * 13 + i * 8) % 75
        draw.line((x, y, x + 2, y + 6), fill=tuple(round(v * gain) for v in (53, 84, 125)))
    if i in (10, 12):
        draw.line([(179, 59), (168, 79), (179, 77), (162, 102)], fill=(111, 132, 175), width=1)
    frames.append(frame)

hold = 36
payload = bytearray()
for frame in frames:
    runs = [(sum(1 for _ in run), color) for color, run in groupby(map(rgb565, frame.get_flattened_data()))]
    payload.extend(struct.pack("<II", hold, len(runs)))
    for length, color in runs:
        payload.extend(struct.pack("<HH", length, color))
splash = struct.pack("<4s7I", b"RSP1", len(payload) + 32, zlib.crc32(payload),
                     hold * len(frames), W, H, len(frames), 0) + payload
assert len(splash) <= 24576
header("splash_data.h", array("kSplash", splash, "uint8_t"))
frames[0].save(ROOT.parent / "开机动画.gif", save_all=True, append_images=frames[1:],
               duration=hold, loop=0, disposal=2)
print(f"{len(frames)} frames, {len(splash)} bytes")
